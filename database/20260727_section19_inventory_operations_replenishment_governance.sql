CREATE TABLE IF NOT EXISTS inventory_transfer_requests (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    transfer_number VARCHAR(80) NOT NULL UNIQUE,
    source_company_id BIGINT UNSIGNED NOT NULL,
    destination_company_id BIGINT UNSIGNED NOT NULL,
    source_inventory_location_id BIGINT UNSIGNED NOT NULL,
    destination_inventory_location_id BIGINT UNSIGNED NOT NULL,
    project_workorder_id BIGINT UNSIGNED NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'draft',
    required_date DATE NOT NULL,
    shipped_at DATETIME NULL,
    received_at DATETIME NULL,
    carrier VARCHAR(160) NULL,
    tracking_number VARCHAR(160) NULL,
    freight_cost DECIMAL(15,2) NOT NULL DEFAULT 0,
    owner_id BIGINT UNSIGNED NOT NULL,
    reviewer_id BIGINT UNSIGNED NOT NULL,
    approval_id BIGINT UNSIGNED NULL,
    evidence_note TEXT NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    KEY idx_inventory_transfer_source (source_company_id,status,required_date),
    KEY idx_inventory_transfer_destination (destination_company_id,status,required_date),
    KEY idx_inventory_transfer_approval (approval_id),
    CONSTRAINT fk_inventory_transfer_source_company FOREIGN KEY (source_company_id) REFERENCES companies(id),
    CONSTRAINT fk_inventory_transfer_destination_company FOREIGN KEY (destination_company_id) REFERENCES companies(id),
    CONSTRAINT fk_inventory_transfer_source_location FOREIGN KEY (source_inventory_location_id) REFERENCES inventory_locations(id),
    CONSTRAINT fk_inventory_transfer_destination_location FOREIGN KEY (destination_inventory_location_id) REFERENCES inventory_locations(id),
    CONSTRAINT fk_inventory_transfer_project FOREIGN KEY (project_workorder_id) REFERENCES projects_workorders(id),
    CONSTRAINT fk_inventory_transfer_owner FOREIGN KEY (owner_id) REFERENCES users(id),
    CONSTRAINT fk_inventory_transfer_reviewer FOREIGN KEY (reviewer_id) REFERENCES users(id),
    CONSTRAINT fk_inventory_transfer_approval FOREIGN KEY (approval_id) REFERENCES workflow_approvals(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS inventory_transfer_lines (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    transfer_request_id BIGINT UNSIGNED NOT NULL,
    item_id BIGINT UNSIGNED NOT NULL,
    quantity_requested DECIMAL(15,4) NOT NULL,
    quantity_shipped DECIMAL(15,4) NOT NULL DEFAULT 0,
    quantity_received DECIMAL(15,4) NOT NULL DEFAULT 0,
    unit_cost DECIMAL(15,4) NOT NULL DEFAULT 0,
    serial_or_lot_reference VARCHAR(240) NULL,
    condition_status VARCHAR(32) NOT NULL DEFAULT 'pending',
    notes TEXT NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_inventory_transfer_item (transfer_request_id,item_id),
    KEY idx_inventory_transfer_line_item (item_id),
    CONSTRAINT fk_inventory_transfer_line_request FOREIGN KEY (transfer_request_id) REFERENCES inventory_transfer_requests(id) ON DELETE CASCADE,
    CONSTRAINT fk_inventory_transfer_line_item FOREIGN KEY (item_id) REFERENCES items(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

