SET NAMES utf8mb4;
SET time_zone = '+00:00';

CREATE TABLE IF NOT EXISTS inventory_replenishment_policies (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    policy_number VARCHAR(80) NOT NULL UNIQUE,
    company_id BIGINT UNSIGNED NOT NULL,
    inventory_location_id BIGINT UNSIGNED NOT NULL,
    item_id BIGINT UNSIGNED NOT NULL,
    minimum_quantity DECIMAL(15,4) NOT NULL DEFAULT 0,
    maximum_quantity DECIMAL(15,4) NOT NULL DEFAULT 0,
    reorder_point DECIMAL(15,4) NOT NULL DEFAULT 0,
    safety_stock DECIMAL(15,4) NOT NULL DEFAULT 0,
    lead_time_days INT UNSIGNED NOT NULL DEFAULT 1,
    review_frequency_days INT UNSIGNED NOT NULL DEFAULT 7,
    preferred_supplier_id BIGINT UNSIGNED NULL,
    owner_id BIGINT UNSIGNED NOT NULL,
    reviewer_id BIGINT UNSIGNED NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'active',
    evidence_note TEXT NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_inventory_replenishment_policy (inventory_location_id,item_id),
    KEY idx_inventory_policy_company_status (company_id,status),
    KEY idx_inventory_policy_item (item_id),
    CONSTRAINT fk_inventory_policy_company FOREIGN KEY (company_id) REFERENCES companies(id),
    CONSTRAINT fk_inventory_policy_location FOREIGN KEY (inventory_location_id) REFERENCES inventory_locations(id),
    CONSTRAINT fk_inventory_policy_item FOREIGN KEY (item_id) REFERENCES items(id),
    CONSTRAINT fk_inventory_policy_supplier FOREIGN KEY (preferred_supplier_id) REFERENCES suppliers(id),
    CONSTRAINT fk_inventory_policy_owner FOREIGN KEY (owner_id) REFERENCES users(id),
    CONSTRAINT fk_inventory_policy_reviewer FOREIGN KEY (reviewer_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

